import fs from 'node:fs'
import path from 'node:path'
import { findListPath, shapeOf, shapeToTs, valueAt } from './shape.js'
import type { FlowModel, FormField, NamedCall, Shape } from './types.js'

export function emitFlow(flow: FlowModel, outDir: string): string[] {
  fs.mkdirSync(outDir, { recursive: true })
  const componentName = flow.framework === 'angular' ? `${flow.kebab}.component.ts` : `${flow.name}.tsx`
  const files: Array<[string, string]> = [
    ['evidence.md', renderEvidence(flow)],
    ['flow.json', renderFlowJson(flow)],
    ['api.ts', renderApi(flow)],
    [componentName, flow.framework === 'angular' ? renderAngular(flow) : renderReact(flow)],
  ]
  for (const [name, contents] of files) fs.writeFileSync(path.join(outDir, name), contents)
  return files.map(([name]) => name)
}

export function renderEvidence(flow: FlowModel): string {
  const lines = [
    `# ${flow.name}`,
    '',
    'Flowshot kept the application calls from a HAR you supplied. Static files were left out. Cookies, authorization headers, and secret-looking values were not copied.',
    '',
    `Ignored ${flow.ignoredCount} other request${flow.ignoredCount === 1 ? '' : 's'}.`,
    '',
    '| # | Method | Path | Status | ms | Response |',
    '| --- | --- | --- | --- | --- | --- |',
  ]
  flow.calls.forEach((call, index) => {
    const response = call.bodyMissing ? 'not stored in the HAR' : call.responseJson === undefined ? 'not JSON' : 'recorded'
    lines.push(`| ${index + 1} | ${call.method} | \`${call.displayPath}\` | ${call.status} | ${call.timeMs} | ${response} |`)
  })

  for (const call of flow.calls) {
    lines.push('', `## ${call.method} ${call.displayPath}`, '')
    if (call.query.length > 0) {
      lines.push('Query', '', '| Name | Example |', '| --- | --- |')
      for (const query of call.query) lines.push(`| ${query.name} | ${inlineCode(query.value)} |`)
      lines.push('')
    }
    if (call.requestJson !== undefined) {
      lines.push('Request shape', '', '```ts', shapeToTs(shapeOf(call.requestJson)), '```', '')
    }
    if (call.responseJson !== undefined) {
      lines.push('Response shape', '', '```ts', shapeToTs(shapeOf(call.responseJson)), '```', '')
    } else if (call.bodyMissing) {
      lines.push('The HAR did not include this response body. Export again with content if you need the shape.', '')
    }
  }

  const result = flow.calls[flow.resultCallIndex]
  lines.push(
    '## Component',
    '',
    `\`${flow.name}\` submits the captured fields and renders the result of \`${result?.method ?? ''} ${result?.displayPath ?? ''}\`.`,
    '',
    '## Limits',
    '',
    '- The component is a starting point grounded in the capture, not a visual copy of a screen.',
    '- Replay does not send the original cookies or authorization header. Add your own session in the app that hosts the component.',
    '- Use this on a flow you recorded yourself and are allowed to examine.',
    '',
  )
  return `${lines.join('\n')}\n`
}

function renderFlowJson(flow: FlowModel): string {
  return `${JSON.stringify({
    version: 1,
    name: flow.name,
    framework: flow.framework,
    ignoredCount: flow.ignoredCount,
    resultCallIndex: flow.resultCallIndex,
    listPath: flow.listPath,
    formFields: flow.formFields.map((field) => ({
      name: field.name,
      source: field.source,
      example: field.example,
      valueKind: field.valueKind,
    })),
    calls: flow.calls.map((call) => ({
      method: call.method,
      origin: call.origin,
      path: call.displayPath,
      status: call.status,
      timeMs: call.timeMs,
      functionName: call.functionName,
      query: call.query,
      request: call.requestJson ?? null,
      response: call.responseJson ?? null,
      bodyMissing: call.bodyMissing,
    })),
  }, null, 2)}\n`
}

function renderApi(flow: FlowModel): string {
  const blocks = [
    '// Generated by Flowshot from a HAR capture.',
    '// Review the endpoints before sending real user data.',
    '',
  ]
  for (const call of flow.calls) blocks.push(renderFunction(call), '')
  return blocks.join('\n')
}

function renderFunction(call: NamedCall): string {
  const typeBase = pascal(call.functionName)
  const responseShape = call.responseJson === undefined ? null : shapeOf(call.responseJson)
  const itemShape = responseShape ? listItemShape(call, responseShape) : null
  const lines: string[] = []
  if (call.inputFields.length > 0) {
    lines.push(`export type ${typeBase}Input = { ${call.inputFields.map((field) => `${field.ident}: ${field.valueKind}`).join('; ')} }`, '')
  }
  if (itemShape) lines.push(`export type ${typeBase}Item = ${shapeToTs(itemShape)}`, '')
  if (responseShape) lines.push(`export type ${typeBase}Response = ${shapeToTs(responseShape)}`, '')

  const params = call.inputFields.length > 0 ? `input: ${typeBase}Input, signal?: AbortSignal` : 'signal?: AbortSignal'
  lines.push(`export async function ${call.functionName}(${params}): Promise<${responseShape ? `${typeBase}Response` : 'void'}> {`)
  const pathField = call.inputFields.find((field) => field.source === 'path')
  if (pathField) {
    lines.push(`  const path = ${JSON.stringify(templatePath(call.path))}.replaceAll('{id}', encodeURIComponent(String(input.${pathField.ident})))`)
    lines.push(`  const url = new URL(path, ${JSON.stringify(call.origin)})`)
  } else {
    lines.push(`  const url = new URL(${JSON.stringify(call.path)}, ${JSON.stringify(call.origin)})`)
  }
  for (const field of call.inputFields.filter((item) => item.source === 'query')) {
    lines.push(`  url.searchParams.set(${JSON.stringify(field.name)}, String(input.${field.ident}))`)
  }
  const bodyFields = call.inputFields.filter((field) => field.source === 'body')
  lines.push('  const response = await fetch(url, {')
  lines.push(`    method: ${JSON.stringify(call.method)},`)
  lines.push('    signal,')
  lines.push('    headers: {')
  lines.push(bodyFields.length > 0 ? "      accept: 'application/json'," : "      accept: 'application/json',")
  if (bodyFields.length > 0) lines.push("      'content-type': 'application/json',")
  lines.push('    },')
  if (bodyFields.length > 0) {
    lines.push(`    body: JSON.stringify({ ${bodyFields.map((field) => `${JSON.stringify(field.name)}: input.${field.ident}`).join(', ')} }),`)
  }
  lines.push('  })')
  lines.push('  if (!response.ok) {')
  lines.push(`    throw new Error(${JSON.stringify(`${call.method} ${call.displayPath} failed`)} + \` (\${response.status})\`)`)
  lines.push('  }')
  if (responseShape) lines.push(`  return (await response.json()) as ${typeBase}Response`)
  lines.push('}')
  return lines.join('\n')
}

function renderReact(flow: FlowModel): string {
  const result = flow.calls[flow.resultCallIndex]!
  const itemType = itemTypeName(result)
  const lines = [
    '// Generated by Flowshot from a HAR capture.',
    "import { useState, type FormEvent } from 'react'",
    `import { ${flow.calls.map((call) => call.functionName).join(', ')} } from './api'`,
  ]
  if (itemType) lines.push(`import type { ${itemType} } from './api'`)
  lines.push('', `export function ${flow.name}() {`)
  for (const field of flow.formFields) {
    lines.push(`  const [${field.ident}, ${setter(field.ident)}] = useState(${JSON.stringify(field.example)})`)
  }
  lines.push(itemType ? `  const [items, setItems] = useState<${itemType}[]>([])` : "  const [resultText, setResultText] = useState('')")
  lines.push('  const [loading, setLoading] = useState(false)', "  const [error, setError] = useState('')", '')
  lines.push('  async function onSubmit(event: FormEvent<HTMLFormElement>) {')
  lines.push("    event.preventDefault()", '    setLoading(true)', "    setError('')", '    try {')
  lines.push(...callStatements(flow, ''))
  lines.push('    } catch (caught) {')
  lines.push(itemType ? '      setItems([])' : "      setResultText('')")
  lines.push("      setError(caught instanceof Error ? caught.message : 'Request failed')")
  lines.push('    } finally {', '      setLoading(false)', '    }', '  }', '')
  lines.push('  return (', '    <form onSubmit={onSubmit}>')
  for (const field of flow.formFields) {
    lines.push('      <label>', `        ${escapeText(field.label)}`)
    lines.push(`        <input value={${field.ident}} onChange={(event) => ${setter(field.ident)}(event.target.value)} />`)
    lines.push('      </label>')
  }
  lines.push('      <button type="submit" disabled={loading}>{loading ? \'Loading…\' : \'Run\'}</button>')
  lines.push('      {error ? <p role="alert">{error}</p> : null}')
  lines.push(...(itemType ? renderReactList(result) : ['      {resultText ? <pre>{resultText}</pre> : null}']))
  lines.push('    </form>', '  )', '}', '')
  return lines.join('\n')
}

function renderReactList(result: NamedCall): string[] {
  const listed = result.responseJson === undefined ? null : shapeOf(valueAt(result.responseJson, findListPath(result.responseJson) ?? []))
  const fields = listed?.kind === 'array' && listed.item.kind === 'object' ? listed.item.fields : []
  const key = fields.find((field) => !field.optional && (field.name === 'id' || field.name === 'uuid') && (field.shape.kind === 'string' || field.shape.kind === 'number'))
  const title = stringField(fields, /title|name|label|heading/i) ?? stringField(fields, /.*/)
  const extra = fields.find((field) => field !== title && field.shape.kind === 'string')
  const keyExpr = key ? `item.${safeProp(key.name)}` : 'index'
  const params = key ? 'item' : 'item, index'
  const lines = [
    '      <ul>',
    `        {items.map((${params}) => (`,
    `          <li key={${keyExpr}}>`,
    `            <strong>{${title ? `item.${safeProp(title.name)}` : 'JSON.stringify(item)'}}</strong>`,
  ]
  if (extra) lines.push(`            <div>{item.${safeProp(extra.name)}}</div>`)
  lines.push('          </li>', '        ))}', '      </ul>')
  return lines
}

function renderAngular(flow: FlowModel): string {
  const result = flow.calls[flow.resultCallIndex]!
  const itemType = itemTypeName(result)
  const lines = [
    '// Generated by Flowshot from a HAR capture.',
    "import { Component } from '@angular/core'",
    `import { ${flow.calls.map((call) => call.functionName).join(', ')} } from './api'`,
  ]
  if (itemType) lines.push(`import type { ${itemType} } from './api'`)
  lines.push('', '@Component({', `  selector: 'app-${flow.kebab}',`, '  standalone: true,', '  template: `', '    <form (submit)="onSubmit($event)">')
  for (const field of flow.formFields) {
    lines.push(`      <label>${escapeText(field.label)} <input [value]="${field.ident}" (input)="${field.ident} = $any($event.target).value" /></label>`)
  }
  lines.push('      <button type="submit" [disabled]="loading">{{ loading ? \'Loading…\' : \'Run\' }}</button>')
  lines.push('      @if (error) { <p role="alert">{{ error }}</p> }')
  if (itemType) lines.push('      <ul>', '        @for (item of items; track $index) { <li>{{ itemLabel(item) }}</li> }', '      </ul>')
  else lines.push('      @if (resultText) { <pre>{{ resultText }}</pre> }')
  lines.push('    </form>', '  `,', '})', `export class ${flow.name}Component {`)
  for (const field of flow.formFields) lines.push(`  ${field.ident} = ${JSON.stringify(field.example)}`)
  lines.push(itemType ? `  items: ${itemType}[] = []` : "  resultText = ''")
  lines.push('  loading = false', "  error = ''", '', '  async onSubmit(event: Event) {')
  lines.push("    event.preventDefault()", '    this.loading = true', "    this.error = ''", '    try {')
  lines.push(...callStatements(flow, 'this.'))
  lines.push('    } catch (caught) {')
  lines.push(itemType ? '      this.items = []' : "      this.resultText = ''")
  lines.push("      this.error = caught instanceof Error ? caught.message : 'Request failed'")
  lines.push('    } finally {', '      this.loading = false', '    }', '  }')
  if (itemType) {
    const listed = result.responseJson === undefined ? null : shapeOf(valueAt(result.responseJson, flow.listPath))
    const fields = listed?.kind === 'array' && listed.item.kind === 'object' ? listed.item.fields : []
    const title = stringField(fields, /title|name|label|heading/i) ?? stringField(fields, /.*/)
    lines.push('', `  itemLabel(item: ${itemType}) {`)
    lines.push(title ? `    return item.${safeProp(title.name)} ?? ''` : '    return JSON.stringify(item)')
    lines.push('  }')
  }
  lines.push('}', '')
  return lines.join('\n')
}

function callStatements(flow: FlowModel, prefix: string): string[] {
  const result = flow.calls[flow.resultCallIndex]!
  const itemType = itemTypeName(result)
  const lines: string[] = []
  for (const call of flow.calls) {
    const args = callArgs(call, prefix)
    if (call !== result) {
      lines.push(`      await ${call.functionName}(${args})`)
      continue
    }
    if (itemType) {
      lines.push(`      const loaded = await ${call.functionName}(${args})`)
      const items = `${accessPath('loaded', flow.listPath)} ?? []`
      lines.push(prefix === 'this.' ? `      this.items = ${items}` : `      setItems(${items})`)
      continue
    }
    if (call.responseJson !== undefined) {
      lines.push(`      const loaded = await ${call.functionName}(${args})`)
      const text = 'JSON.stringify(loaded, null, 2)'
      lines.push(prefix === 'this.' ? `      this.resultText = ${text}` : `      setResultText(${text})`)
      continue
    }
    lines.push(`      await ${call.functionName}(${args})`)
  }
  return lines
}

function callArgs(call: NamedCall, prefix: string): string {
  if (call.inputFields.length === 0) return ''
  const fields = call.inputFields.map((field) => {
    const expr = valueExpr(field, prefix)
    return expr === field.ident ? field.ident : `${field.ident}: ${expr}`
  })
  return `{ ${fields.join(', ')} }`
}

function valueExpr(field: FormField, prefix: string): string {
  const raw = `${prefix}${field.ident}`
  if (field.source === 'body' && field.valueKind === 'number') return `Number(${raw})`
  if (field.source === 'body' && field.valueKind === 'boolean') return `${raw} === 'true'`
  return raw
}

function accessPath(root: string, listPath: string[]): string {
  return listPath.reduce((current, key) => `${current}.${safeProp(key)}`, root)
}

function itemTypeName(call: NamedCall): string | null {
  if (call.responseJson === undefined) return null
  const shape = listItemShape(call, shapeOf(call.responseJson))
  return shape ? `${pascal(call.functionName)}Item` : null
}

function listItemShape(call: NamedCall, response: Shape): Shape | null {
  if (call.responseJson === undefined) return null
  const listed = shapeAt(response, findListPath(call.responseJson) ?? [])
  if (!findListPath(call.responseJson)) return null
  if (listed?.kind === 'array' && listed.item.kind === 'object') return listed.item
  return null
}

function shapeAt(shape: Shape, path: string[]): Shape | null {
  return path.reduce<Shape | null>((current, key) => {
    if (!current || current.kind !== 'object') return null
    return current.fields.find((field) => field.name === key)?.shape ?? null
  }, shape)
}

function stringField(fields: Array<{ name: string; shape: Shape }>, pattern: RegExp): { name: string; shape: Shape } | undefined {
  return fields.find((field) => field.shape.kind === 'string' && pattern.test(field.name))
}

function templatePath(pathname: string): string {
  return pathname
    .split('/')
    .map((segment) => (/^\d+$/.test(segment) || /^[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i.test(segment) ? '{id}' : segment))
    .join('/')
}

function pascal(camel: string): string {
  return camel.charAt(0).toUpperCase() + camel.slice(1)
}

function setter(ident: string): string {
  return `set${ident.charAt(0).toUpperCase()}${ident.slice(1)}`
}

function safeProp(name: string): string {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name) ? name : JSON.stringify(name)
}

function inlineCode(value: string): string {
  return `\`${value.replace(/\|/g, '\\|').replace(/`/g, '\\`')}\``
}

function escapeText(value: string): string {
  return value.replace(/[&<>]/g, (char) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;' })[char] ?? char)
}
